import os
import math

def generate_ppm(filename, width, height, pattern_type):
    print(f"Generating input image: {filename} ({width}x{height}, pattern: {pattern_type})...")
    with open(filename, 'wb') as f:
        # PPM binary format header
        f.write(f"P6\n# Procedural pattern: {pattern_type}\n{width} {height}\n255\n".encode('ascii'))
        data = bytearray()
        for y in range(height):
            for x in range(width):
                if pattern_type == 'gradient':
                    r = int(x / width * 255)
                    g = int(y / height * 255)
                    b = 128
                elif pattern_type == 'checkerboard':
                    val = 255 if ((x // 32) + (y // 32)) % 2 == 0 else 0
                    r = val
                    g = 128 if val == 255 else 0
                    b = 255 - val
                elif pattern_type == 'colorwheel':
                    cx, cy = width / 2.0, height / 2.0
                    dx, dy = x - cx, y - cy
                    dist = math.sqrt(dx*dx + dy*dy)
                    max_dist = math.sqrt(cx*cx + cy*cy)
                    r = int((dx / cx + 1.0) * 127) if cx > 0 else 0
                    g = int((dy / cy + 1.0) * 127) if cy > 0 else 0
                    b = int((1.0 - dist / max_dist) * 255) if max_dist > 0 else 0
                else: # stripes
                    r = int((x // 20) % 3 == 0) * 255
                    g = int((x // 20) % 3 == 1) * 255
                    b = int((x // 20) % 3 == 2) * 255
                
                # Clamp values
                r = max(0, min(255, r))
                g = max(0, min(255, g))
                b = max(0, min(255, b))
                
                data.append(r)
                data.append(g)
                data.append(b)
        f.write(data)

def convert_to_grayscale(in_filename, out_filename):
    print(f"Converting {in_filename} -> {out_filename}...")
    with open(in_filename, 'rb') as f:
        # Simple PPM P6 parser
        header = f.readline().decode('ascii').strip()
        if header != 'P6':
            raise ValueError("Unsupported format, must be P6 PPM")
        
        # Skip comments
        line = f.readline().decode('ascii')
        while line.startswith('#'):
            line = f.readline().decode('ascii')
        
        # Dimensions
        dims = line.strip().split()
        if len(dims) == 2:
            width, height = int(dims[0]), int(dims[1])
            max_val = int(f.readline().decode('ascii').strip())
        else:
            # Dims and max_val might be on different lines
            width = int(dims[0])
            height = int(f.readline().decode('ascii').strip())
            max_val = int(f.readline().decode('ascii').strip())
            
        data = f.read()
        
    gray_data = bytearray()
    for i in range(width * height):
        r = data[i * 3]
        g = data[i * 3 + 1]
        b = data[i * 3 + 2]
        # BT.601 Formula
        gray = int(0.299 * r + 0.587 * g + 0.114 * b)
        gray_data.append(max(0, min(255, gray)))
        
    with open(out_filename, 'wb') as f:
        f.write(f"P5\n# Generated by CUDA Grayscale Converter\n{width} {height}\n{max_val}\n".encode('ascii'))
        f.write(gray_data)

